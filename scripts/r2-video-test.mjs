import { chromium } from 'playwright';
const out = process.env.OUT;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('PAGEERR', e.message));
p.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await p.goto('http://localhost:5387/miguel');
await p.waitForTimeout(1200);
await p.keyboard.press('Space');
await p.waitForTimeout(2500);
await p.keyboard.press('e');
const dl = p.waitForEvent('download', { timeout: 240000 });
await p.click('button.key:has-text("▶ FILM")');
await p.waitForSelector('.prog.done', { timeout: 240000 });
await p.click('button.key:has-text("SAVE")');
const d = await dl;
const fn = await d.suggestedFilename();
await d.saveAs(out + '/' + fn);
console.log('video saved:', fn);
await b.close();
console.log('DONE');
